-- Slug and seat counters are owned by the database, not the browser.
create or replace function public.events_before_write()
returns trigger language plpgsql as $$
declare v_sold integer;
begin
  if tg_op = 'INSERT' then
    if new.slug is null or btrim(new.slug) = '' then
      new.slug := public.slugify(new.title) || '-' || substr(md5(random()::text || clock_timestamp()::text), 1, 6);
    end if;
    new.available_seats := new.total_seats;
  else
    new.slug := old.slug;
    if new.total_seats <> old.total_seats then
      v_sold := old.total_seats - old.available_seats;
      if new.total_seats < v_sold then
        raise exception 'Total seats cannot be lower than the % seats already booked.', v_sold;
      end if;
      new.available_seats := new.total_seats - v_sold;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists events_before_write on public.events;
create trigger events_before_write before insert or update on public.events
  for each row execute function public.events_before_write();

-- A cancelled booking can never be re-opened, and cancelling gives the seats back.
create or replace function public.bookings_guard_status()
returns trigger language plpgsql as $$
begin
  if old.status = 'cancelled' and new.status <> 'cancelled' then
    raise exception 'Cancelled bookings cannot be reopened.';
  end if;
  return new;
end;
$$;

drop trigger if exists bookings_guard_status on public.bookings;
create trigger bookings_guard_status before update of status on public.bookings
  for each row execute function public.bookings_guard_status();

create or replace function public.bookings_release_seats()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'cancelled' and old.status <> 'cancelled' then
    update public.events
       set available_seats = least(total_seats, available_seats + old.num_tickets)
     where event_id = old.event_id;
    if old.ticket_type_id is not null then
      update public.ticket_types
         set sold = greatest(0, sold - old.num_tickets)
       where ticket_type_id = old.ticket_type_id;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists bookings_release_seats on public.bookings;
create trigger bookings_release_seats after update of status on public.bookings
  for each row execute function public.bookings_release_seats();

-- ---------- role helpers (used by RLS) ---------------------
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where user_id = auth.uid() and role_id = 1 and is_active);
$$;

create or replace function public.is_organizer()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where user_id = auth.uid() and role_id in (1, 2) and is_active);
$$;

-- Organizers may see the profile of people who booked THEIR events.
create or replace function public.organizer_can_see_profile(p_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1
    from public.bookings b
    join public.events e on e.event_id = b.event_id
    where b.user_id = p_user_id and e.organizer_id = auth.uid()
  );
$$;

