-- ---------- RPC: create a booking (atomic) -----------------
drop function if exists public.create_booking(bigint, integer, bigint);

create or replace function public.create_booking(
  p_event_id       bigint,
  p_num_tickets    integer default 1,
  p_ticket_type_id bigint  default null,
  p_method         text    default 'cash'
)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid        uuid := auth.uid();
  v_event      public.events%rowtype;
  v_tt         public.ticket_types%rowtype;
  v_price      numeric(10,2);
  v_total      numeric(10,2);
  v_ref        text;
  v_booking_id bigint;
  v_status     text;
begin
  if v_uid is null then raise exception 'Please login before booking.'; end if;
  if not exists (select 1 from public.profiles where user_id = v_uid and is_active) then
    raise exception 'Your account is inactive.';
  end if;
  if p_num_tickets is null or p_num_tickets < 1 or p_num_tickets > 10 then
    raise exception 'You can book between 1 and 10 tickets.';
  end if;
  if p_method not in ('cash', 'card', 'bank_transfer', 'easypaisa', 'jazzcash') then
    raise exception 'Invalid payment method.';
  end if;

  select * into v_event from public.events
   where event_id = p_event_id and status = 'published'
   for update;
  if not found then raise exception 'Event not found or not available.'; end if;
  if v_event.event_date < current_date then raise exception 'This event has already taken place.'; end if;
  if v_event.available_seats < p_num_tickets then raise exception 'Not enough seats available.'; end if;

  v_price := v_event.ticket_price;
  if p_ticket_type_id is not null then
    select * into v_tt from public.ticket_types
     where ticket_type_id = p_ticket_type_id and event_id = p_event_id
     for update;
    if not found then raise exception 'Invalid ticket type for this event.'; end if;
    if v_tt.quantity - v_tt.sold < p_num_tickets then raise exception 'Not enough tickets of this type left.'; end if;
    v_price := v_tt.price;
    update public.ticket_types set sold = sold + p_num_tickets where ticket_type_id = p_ticket_type_id;
  end if;

  v_total  := v_price * p_num_tickets;
  v_status := case when v_total = 0 then 'confirmed' else 'pending' end;
  v_ref    := 'EMS-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.booking_ref_seq')::text, 5, '0');

  insert into public.bookings (user_id, event_id, ticket_type_id, booking_ref, num_tickets, total_amount, status)
  values (v_uid, p_event_id, p_ticket_type_id, v_ref, p_num_tickets, v_total, v_status)
  returning booking_id into v_booking_id;

  insert into public.payments (booking_id, amount, method, status, transaction_ref, paid_at)
  values (
    v_booking_id, v_total, p_method,
    case when v_total = 0 then 'completed' else 'pending' end,
    case when v_total = 0 then 'FREE-' || v_ref else null end,
    case when v_total = 0 then now() else null end
  );

  update public.events set available_seats = available_seats - p_num_tickets where event_id = p_event_id;

  return jsonb_build_object('booking_id', v_booking_id, 'booking_ref', v_ref,
                            'total_amount', v_total, 'status', v_status);
end;
$$;

-- ---------- RPC: change booking status ---------------------
create or replace function public.update_booking_status(p_booking_id bigint, p_status text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid  uuid := auth.uid();
  v_role smallint;
  v_b    public.bookings%rowtype;
  v_org  uuid;
begin
  if v_uid is null then raise exception 'Please login first.'; end if;
  select role_id into v_role from public.profiles where user_id = v_uid and is_active;
  if v_role is null then raise exception 'Your account is inactive.'; end if;
  if p_status not in ('pending', 'confirmed', 'cancelled', 'attended') then raise exception 'Invalid status.'; end if;

  select * into v_b from public.bookings where booking_id = p_booking_id for update;
  if not found then raise exception 'Booking not found.'; end if;
  select organizer_id into v_org from public.events where event_id = v_b.event_id;

  if v_role = 1 or (v_role = 2 and v_org = v_uid) then
    null;                                           -- staff: any transition
  elsif v_b.user_id = v_uid then
    if p_status <> 'cancelled' then raise exception 'You can only cancel your own bookings.'; end if;
  else
    raise exception 'Permission denied.';
  end if;

  if v_b.status = 'cancelled' and p_status <> 'cancelled' then raise exception 'Cancelled bookings cannot be reopened.'; end if;
  if v_b.status = 'attended'  and p_status = 'cancelled'  then raise exception 'An attended booking cannot be cancelled.'; end if;

  update public.bookings set status = p_status where booking_id = p_booking_id;

  if p_status in ('confirmed', 'attended') then
    update public.payments
       set status = 'completed',
           paid_at = coalesce(paid_at, now()),
           transaction_ref = coalesce(transaction_ref, 'TXN-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 10)))
     where booking_id = p_booking_id and status = 'pending';
  elsif p_status = 'cancelled' then
    update public.payments
       set status = case status when 'completed' then 'refunded' when 'pending' then 'failed' else status end
     where booking_id = p_booking_id;
  end if;

  return jsonb_build_object('booking_id', p_booking_id, 'status', p_status);
end;
$$;

-- ---------- RPC: dashboard (scoped by role) ----------------
create or replace function public.dashboard_data()
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_uid    uuid := auth.uid();
  v_role   smallint;
  v_result jsonb;
begin
  if v_uid is null then raise exception 'Please login first.'; end if;
  select role_id into v_role from public.profiles where user_id = v_uid and is_active;
  if v_role is null then raise exception 'Your account is inactive.'; end if;

  with ev as (
    select * from public.events
    where v_role = 1
       or (v_role = 2 and organizer_id = v_uid)
       or (v_role = 3 and status = 'published')
  ), bk as (
    select b.* from public.bookings b
    where v_role = 1
       or (v_role = 3 and b.user_id = v_uid)
       or (v_role = 2 and b.event_id in (select event_id from ev))
  ), pay as (
    select p.* from public.payments p join bk on bk.booking_id = p.booking_id
  )
  select jsonb_build_object(
    'stats', jsonb_build_object(
      'total_events',       (select count(*) from ev),
      'published_events',   (select count(*) from ev where status = 'published'),
      'total_users',        case when v_role = 1 then (select count(*) from public.profiles) else 0 end,
      'total_participants', case when v_role = 1 then (select count(*) from public.profiles where role_id = 3) else 0 end,
      'total_bookings',     (select count(*) from bk),
      'confirmed_bookings', (select count(*) from bk where status = 'confirmed'),
      'total_revenue',      (select coalesce(sum(amount), 0) from pay where status = 'completed'),
      'monthly_revenue',    (select coalesce(sum(amount), 0) from pay
                              where status = 'completed' and date_trunc('month', paid_at) = date_trunc('month', now()))
    ),
    'upcoming', (
      select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select e.event_id, e.title, e.event_date, e.available_seats, e.ticket_price,
               c.name as category, v.name as venue
        from ev e
        join public.categories c on c.category_id = e.category_id
        join public.venues v     on v.venue_id    = e.venue_id
        where e.status = 'published' and e.event_date between current_date and current_date + 30
        order by e.event_date asc limit 5
      ) x),
    'recent_bookings', (
      select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select b.booking_ref, u.full_name, e.title, b.total_amount, b.status, b.booked_at
        from bk b
        join public.profiles u on u.user_id = b.user_id
        join public.events e   on e.event_id = b.event_id
        order by b.booked_at desc limit 6
      ) x),
    'revenue_chart', (
      select coalesce(jsonb_agg(x order by x.m), '[]'::jsonb) from (
        select date_trunc('month', paid_at) as m,
               to_char(date_trunc('month', paid_at), 'Mon YYYY') as month,
               sum(amount) as revenue
        from pay
        where status = 'completed' and paid_at >= date_trunc('month', now()) - interval '5 months'
        group by 1, 2
      ) x),
    'category_chart', (
      select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select c.name, count(e.event_id) as count
        from public.categories c
        left join ev e on e.category_id = c.category_id
        group by c.category_id, c.name
        order by count(e.event_id) desc, c.name
      ) x)
  ) into v_result;

  return v_result;
end;
$$;

-- ---------- RPC: reports (admin only) ----------------------
create or replace function public.get_report(p_type text default 'overview')
returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;

  if p_type = 'revenue' then
    return (select coalesce(jsonb_agg(x order by x.month desc), '[]'::jsonb) from (
      select to_char(paid_at, 'YYYY-MM') as month, count(*) as transactions, sum(amount) as revenue
      from public.payments where status = 'completed'
      group by 1 order by 1 desc limit 12) x);

  elsif p_type = 'top_events' then
    return (select coalesce(jsonb_agg(x order by x.total_revenue desc), '[]'::jsonb) from (
      select e.event_id, e.title,
             count(b.booking_id) as total_bookings,
             coalesce(sum(b.total_amount), 0) as total_revenue,
             (e.total_seats - e.available_seats) as seats_sold
      from public.events e
      left join public.bookings b on b.event_id = e.event_id and b.status <> 'cancelled'
      group by e.event_id
      order by coalesce(sum(b.total_amount), 0) desc limit 10) x);

  elsif p_type = 'payments' then
    return (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
      select method, count(*) as count, sum(amount) as total
      from public.payments where status = 'completed' group by method order by sum(amount) desc) x);

  else
    return jsonb_build_object(
      'events_by_status',   (select coalesce(jsonb_agg(x), '[]'::jsonb) from (select status, count(*) as count from public.events   group by status) x),
      'bookings_by_status', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (select status, count(*) as count from public.bookings group by status) x),
      'revenue_today', (select coalesce(sum(amount), 0) from public.payments where status = 'completed' and paid_at::date = current_date),
      'revenue_month', (select coalesce(sum(amount), 0) from public.payments
                         where status = 'completed' and date_trunc('month', paid_at) = date_trunc('month', now())),
      'top_venue', (select to_jsonb(x) from (
                      select v.name, count(e.event_id) as events
                      from public.venues v left join public.events e on e.venue_id = v.venue_id
                      group by v.venue_id order by count(e.event_id) desc, v.name limit 1) x)
    );
  end if;
end;
$$;

-- ---------- RPC: user administration (admin only) ----------
create or replace function public.admin_list_users()
returns table (
  user_id uuid, full_name text, email text, phone text,
  role_id smallint, role_name text, is_active boolean,
  created_at timestamptz, total_bookings bigint
)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;
  return query
    select u.user_id, u.full_name, u.email, u.phone, u.role_id, r.role_name, u.is_active, u.created_at,
           count(b.booking_id)
    from public.profiles u
    join public.roles r on r.role_id = u.role_id
    left join public.bookings b on b.user_id = u.user_id
    group by u.user_id, r.role_name
    order by u.created_at desc;
end;
$$;

create or replace function public.admin_update_user(
  p_user_id   uuid,
  p_role_id   smallint default null,
  p_is_active boolean  default null
)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admin access required.'; end if;
  if p_user_id = auth.uid() and (
       (p_role_id is not null and p_role_id <> 1) or p_is_active is false) then
    raise exception 'You cannot demote or deactivate your own admin account.';
  end if;
  update public.profiles
     set role_id   = coalesce(p_role_id, role_id),
         is_active = coalesce(p_is_active, is_active)
   where user_id = p_user_id;
  if not found then raise exception 'User not found.'; end if;
end;
$$;

